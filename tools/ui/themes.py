#!/usr/bin/env python3
"""Compile the locked nine-theme source, without adjusting colour values."""
import argparse
import hashlib
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'docs/reference/themes9.json'
OUTPUT=ROOT/'src/ui/generated/themes9.inc'
NAMES=['POP 1','POP 2','NEON 1','NEON 2','VIVID 1','VIVID 3','CYBER 2','CYBER 3','MONOTONE 1']
FIELDS={'bg':'background',**{x:x for x in ['surface','raised','border','text','secondary','dim','accent','warn','danger','mod','orange','motion']}}
def generate():
    raw=SOURCE.read_bytes();data=json.loads(raw);assert list(data)==NAMES
    def color(value):
        assert len(value)==7 and value[0]=='#'
        return '0xff'+value[1:].lower()+'u'
    def assignments(theme):
        return ''.join(f't.{field}={color(theme["tokens"][token])};' for token,field in FIELDS.items())+'t.disabled=t.dim;t.chassis=t.inset=t.background;t.value_edit=t.teal=t.accent;t.amber=t.warn;t.red=t.danger;t.blue=t.mod;'+''.join(f't.track[{i}]={color(c)};' for i,c in enumerate(theme['tracks']))
    default=data['CYBER 2'];lines=['// Generated by tools/ui/themes.py; exact themes9.json SHA256 '+hashlib.sha256(raw).hexdigest()]
    lines += [f' uint32_t {field}={color(default["tokens"][token])};' for token,field in FIELDS.items()]
    lines += [' uint32_t chassis=background,inset=background,disabled=dim,value_edit=accent,teal=accent,amber=warn,red=danger,blue=mod;',' uint32_t track[16]={'+','.join(color(c) for c in default['tracks'])+'};',' static constexpr unsigned kCount=9,kDefault=6;',' static const Theme& by_index(unsigned i){static const Theme themes[kCount]={']
    lines += ['  []{Theme t;'+assignments(data[name])+('t.monochrome=true;' if name=='MONOTONE 1' else '')+'return t;}(),' for name in NAMES]
    lines += [' };return themes[i<kCount?i:kDefault];}', ' static const char* name(unsigned i){static const char* names[kCount]={'+','.join(json.dumps(name) for name in NAMES)+'};return names[i<kCount?i:kDefault];}']
    return '\n'.join(lines)+'\n'
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args();content=generate()
    if args.check:
        if OUTPUT.read_text()!=content:raise SystemExit('Theme source drift: run python3 tools/ui/themes.py')
    else:OUTPUT.write_text(content)
