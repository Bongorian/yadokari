#!/usr/bin/env python3
"""Quantize the supplied fixed artwork, encode MK3 pairs, publish/check assets."""
import argparse,hashlib,json,struct
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[2]
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
source=ROOT/'assets/boot/splash-yadokari-480x272.png'
im=Image.open(source).convert('RGB')
if im.size!=(480,272):raise SystemExit('Boot artwork must be the exact approved 480x272 PNG')
values=[((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b in im.getdata()]
pairs=[(values[i]<<16)|values[i+1] for i in range(0,len(values),2)]
def packet(words,side):
 head=bytearray(16);head[:4]=bytes([0x84,0,side,0x60]);struct.pack_into('>HHHH',head,8,0,0,480,272)
 out=bytearray(head);literal=[]
 def flush():
  if literal:out.extend(bytes([0])+len(literal).to_bytes(3,'big')+b''.join(struct.pack('>I',v) for v in literal));literal.clear()
 i=0
 while i<len(words):
  j=i+1
  while j<len(words) and words[j]==words[i]:j+=1
  if j-i>=3:flush();out.extend(bytes([1])+(j-i).to_bytes(3,'big')+struct.pack('>I',words[i]));i=j
  else:literal.append(words[i]);i+=1
 flush();out.extend(bytes([3,0,0,0,0x40,0,side,0]));return bytes(out)
left=packet([0]*65280,0);right=packet(pairs,1)
assert len(right)<=480*64*2+28
text='// Generated by tools/ui/boot_splash.py; approved 480x272 PNG -> exact RGB565 -> MK3 pair RLE.\n'
for name,data in [('Left',left),('Right',right)]:
 text+=f'inline constexpr uint8_t kBootSplash{name}[]={{\n'
 for at in range(0,len(data),24):text+=' '+','.join(f'0x{b:02x}' for b in data[at:at+24])+',\n'
 text+='};\n'
target=ROOT/'src/generated/boot_splash.inc'
if a.check:
 if not target.exists() or target.read_text()!=text:raise SystemExit('Boot splash generated data differs')
else:
 target.write_text(text)
 preview=Image.new('RGB',(960,272));quant=Image.new('RGB',(480,272));quant.putdata([(((v>>11)<<3)|((v>>11)>>2),(((v>>5)&63)<<2)|(((v>>5)&63)>>4),((v&31)<<3)|((v&31)>>2)) for v in values]);preview.paste(quant,(480,0));preview.save(ROOT/'assets/boot/splash-preview.png')
 info={'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'conversion':'Approved PNG at native 480x272 -> truncating RGB565; no resampling, redrawing, thresholding or baked version','left_packet_bytes':len(left),'right_packet_bytes':len(right),'rgb565_sha256':hashlib.sha256(b''.join(struct.pack('>H',v) for v in values)).hexdigest(),'right_packet_sha256':hashlib.sha256(right).hexdigest()}
 (ROOT/'assets/boot/splash-generated.json').write_text(json.dumps(info,indent=2)+'\n')
print('Boot splash wire bytes:',len(left),'+',len(right))
