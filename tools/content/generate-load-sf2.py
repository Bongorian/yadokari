#!/usr/bin/env python3
"""Original final-test SF2: 16 referenced long sample zones, four programs, no padding payload."""
from pathlib import Path
import struct,json,hashlib
p=lambda f,*v:struct.pack('<'+f,*v)
def name(s):return s.encode().ljust(20,b'\0')
def chunk(tag,data):return tag.encode()+p('I',len(data))+data+(b'\0' if len(data)%2 else b'')
def group(tag,*items):return chunk('LIST',tag.encode()+b''.join(items))
frames=1048576;count=16;sample_bytes=(frames+46)*count*2
phdr=b''.join(name('Final '+str(i))+p('HHHIII',i,0,i,0,0,0) for i in range(4))+name('EOP')+p('HHHIII',0,0,4,0,0,0)
pbag=b''.join(p('HH',i,0) for i in range(5));pgen=b''.join(p('HH',41,0) for _ in range(4))+p('HH',0,0)
inst=name('16 zones')+p('H',0)+name('EOI')+p('H',count)
igen=b''.join(p('HHHHHHHHHH',43,(i*8)|((i*8+7)<<8),54,1,38,(-2400)&65535,58,i*8+4,53,i) for i in range(count))+p('HH',0,0)
ibag=b''.join(p('HH',i*5,0) for i in range(count+1));shdr=b'';periods=[]
for i in range(count):
 root=i*8+4;period=round(48000/(440*2**((root-69)/12)));periods.append(period);start=i*(frames+46);end=start+frames
 shdr+=name('Zone '+str(i))+p('IIIIIBbHH',start,end,start,start+period*(frames//period),48000,root,0,0,1)
shdr+=name('EOS')+p('IIIIIBbHH',count*(frames+46),count*(frames+46),0,0,48000,0,0,0,1)
suffix=group('pdta',chunk('phdr',phdr),chunk('pbag',pbag),chunk('pmod',bytes(10)),chunk('pgen',pgen),chunk('inst',inst),chunk('ibag',ibag),chunk('imod',bytes(10)),chunk('igen',igen),chunk('shdr',shdr))
info=group('INFO',chunk('ifil',p('HH',2,1)),chunk('INAM',b'MK3 Final 16-zone generated\0'))
body=b'sfbk'+info+b'LIST'+p('I',4+8+sample_bytes)+b'sdta'+b'smpl'+p('I',sample_bytes)
prefix=b'RIFF'+p('I',len(body)+sample_bytes+len(suffix))+body
header='// Generated by tools/content/generate-load-sf2.py; original procedural debug content.\n#pragma once\n#include <stdint.h>\nnamespace groove {\n'
for n,data in [('kLoadSf2Prefix',prefix),('kLoadSf2Suffix',suffix)]:header+='inline constexpr uint8_t '+n+'[]={'+','.join(map(str,data))+'};\n'
header+='inline constexpr unsigned kLoadSf2Periods[]={'+','.join(map(str,periods))+'};\n}\n'
Path('firmware/load_sf2_metadata.h').write_text(header)
Path('build').mkdir(exist_ok=True)
Path('build/load-sf2-layout.json').write_text(json.dumps({'sample_frames_each':frames,'samples':count,'programs':4,'bytes':len(prefix)+sample_bytes+len(suffix),'periods':periods,'header_sha256':hashlib.sha256(header.encode()).hexdigest(),'scope':'All 16 long mono zones are referenced; procedural spectra, not arbitrary third-party SF2 coverage'},indent=2)+'\n')
