#!/usr/bin/env python3
"""Generate/check the build-side factory roster; never read target DATA."""
import argparse,hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--write',action='store_true');p.add_argument('--revision',type=int);a=p.parse_args()
source=ROOT/'build/factory-data';target=ROOT/'assets/boot/factory-catalog.json';header=ROOT/'src/generated/factory_catalog.inc'
files=[]
for path in sorted(source.rglob('*')):
 if not path.is_file():continue
 relative=path.relative_to(source).as_posix()
 if relative=='FACTORY/KITS/Techno-01.mgxk':continue # Optional external-source kit, recorded at installation.
 data=path.read_bytes();files.append({'path':relative,'size':len(data),'sha256':hashlib.sha256(data).hexdigest()})
if not files:raise SystemExit('Generate build/factory-data first with make factory-catalog')
old=json.loads(target.read_text()) if target.exists() else None
revision=a.revision if a.revision is not None else old['revision'] if old else 1
if revision<1 or revision>0xffffffff:raise SystemExit('Invalid catalog revision')
if a.write and old and files!=old['files'] and revision<=old['revision']:raise SystemExit('Factory content changed: --revision must exceed the previous revision')
digest=hashlib.sha256(json.dumps(files,sort_keys=True,separators=(',',':')).encode()).hexdigest()
manifest={'revision':revision,'sha256':digest,'files':files}
text='// Generated by tools/content/factory_boot_manifest.py; regenerate with an explicit revision bump.\n'
text+=f'inline constexpr unsigned kFactoryCatalogRevision={revision};\n'
text+='inline constexpr uint8_t kFactoryCatalogHash[32]={'+','.join('0x'+digest[i:i+2] for i in range(0,64,2))+'};\n'
text+='inline constexpr FactoryCatalogEntry kFactoryCatalog[]={\n'
for f in files:text+=' {'+json.dumps(f['path'])+','+str(f['size'])+'},\n'
text+='};\n'
if a.write:
 target.write_text(json.dumps(manifest,indent=2)+'\n');header.write_text(text)
elif not old or manifest!=old or not header.exists() or header.read_text()!=text:raise SystemExit('Factory manifest differs: regenerate and bump revision when content changed')
print(f'Factory catalog revision {revision}: {len(files)} files, SHA256 {digest}')
