#!/usr/bin/env python3
"""Locally authored single-loop SF2. No external sound assets. Debug only."""
from pathlib import Path
import struct, math
p=lambda f,*v:struct.pack('<'+f,*v)
def name(s):return s.encode().ljust(20,b'\0')
def chunk(tag,data):return tag.encode()+p('I',len(data))+data+(b'\0' if len(data)%2 else b'')
def group(tag,*items):return chunk('LIST',tag.encode()+b''.join(items))
frames=184
samples=p(str(frames+46)+'h',*([round(8000*math.sin(i*2*math.pi/frames)) for i in range(frames)]+[0]*46))
phdr=b''.join(name(n)+p('HHHIII',program,bank,bag,0,0,0) for n,program,bank,bag in [('Debug Sine',0,0,0),('Debug Alternate',10,128,1),('EOP',0,0,2)])
pbag=p('HHHHHH',0,0,1,0,2,0)
pgen=p('HHHHHH',41,0,41,0,0,0)
inst=name('Sine')+p('H',0)+name('EOI')+p('H',1)
igen=p('HHHHHHHHHH',54,1,38,(-2400)&65535,58,60,53,0,0,0)
ibag=p('HHHH',0,0,4,0)
shdr=name('Sine loop')+p('IIIIIBbHH',0,frames,0,frames,48000,60,0,0,1)+name('EOS')+p('IIIIIBbHH',frames,frames,frames,frames,48000,0,0,0,1)
data=b'sfbk'+group('INFO',chunk('ifil',p('HH',2,1)),chunk('INAM',b'MK3 debug sine\0'))+group('sdta',chunk('smpl',samples))+group('pdta',chunk('phdr',phdr),chunk('pbag',pbag),chunk('pmod',bytes(10)),chunk('pgen',pgen),chunk('inst',inst),chunk('ibag',ibag),chunk('imod',bytes(10)),chunk('igen',igen),chunk('shdr',shdr))
output=chunk('RIFF',data)
Path('build').mkdir(exist_ok=True);Path('build/debug-sine.sf2').write_bytes(output)
Path('src/soundfont_fixture.h').write_text('// Generated by tools/content/generate-sf2-fixture.py. Original debug sine.\n#pragma once\n#include <stdint.h>\nnamespace groove {\ninline constexpr uint8_t kSoundFontFixture[]={\n'+''.join(' '+','.join(str(b) for b in output[i:i+24])+',\n' for i in range(0,len(output),24))+'};\n}\n')
