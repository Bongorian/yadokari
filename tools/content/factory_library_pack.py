#!/usr/bin/env python3
"""Pack repository factory masters for boot-only lossless restoration (GBL1)."""
import argparse, collections, hashlib, json, struct, zlib, re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def pack(data):
    out=bytearray();literal=bytearray();positions={};at=0
    def flush():
        if literal:out.append(len(literal)-1);out.extend(literal);literal.clear()
    while at<len(data):
        length=0;distance=0;key=data[at:at+3]
        for prev in reversed(positions.get(key,())):
            if at-prev>65535:continue
            n=0;limit=min(130,len(data)-at)
            while n<limit and data[prev+n]==data[at+n]:n+=1
            if n>length:length,distance=n,at-prev
            if n==limit:break
        used=length if length>=3 else 1
        if length>=3:flush();out.append(128+length-3);out.extend(struct.pack('<H',distance))
        else:
            literal.append(data[at])
            if len(literal)==128:flush()
        for pos in range(at,at+used):
            key=data[pos:pos+3]
            if len(key)==3:
                q=positions.setdefault(key,collections.deque(maxlen=8));q.append(pos)
        at+=used
    flush();return bytes(out)
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--write',action='store_true');a=p.parse_args()
    source=ROOT/'assets/factory-library';entries=[];packed=bytearray();seen=set()
    allocation=json.loads((source/'identities.json').read_text());rows=allocation['files']
    assignments={row['master']:row for row in rows}
    if len(assignments)!=len(rows) or len({row['guid'] for row in rows})!=len(rows):raise SystemExit('Duplicate fixed factory path/GUID allocation')
    # Allocation may precede counterpart delivery. Only explicitly pending
    # paths are omitted; missing shipped masters and premature additions fail.
    pending=allocation.get('pending_factory_import',[])
    if len(set(pending))!=len(pending) or set(pending)-set(assignments):raise SystemExit('Invalid pending factory allocation')
    all_guids=[row['guid'] for row in rows+allocation.get('builtins',[])]
    if any(not re.fullmatch('[0-9a-f]{32}',guid) or int(guid,16)==0 for guid in all_guids) or len(set(all_guids))!=len(all_guids):raise SystemExit('Invalid/colliding factory or builtin GUID allocation')
    required=set(assignments)-set(pending)
    masters=sorted(source.rglob('*.mgx*'));actual={file.relative_to(source).as_posix() for file in masters}
    if actual!=required:raise SystemExit(f'Factory master inventory differs from fixed allocation; missing={sorted(required-actual)}, extra={sorted(actual-required)}')
    version=int(re.search(r'kFormatVersion\s*=\s*(\d+)',(ROOT/'src/project_format_version.h').read_text())[1])
    for file in masters:
        data=file.read_bytes();relative=file.relative_to(source).as_posix();kind=data[22] if len(data)>22 else 0
        if data[:4]!=b'MGXC' or struct.unpack_from('<H',data,4)[0]!=version or data[10:14]!=b'TYPE' or kind not in (2,3) or zlib.crc32(data[4:-4])!=struct.unpack_from('<I',data,len(data)-4)[0]:raise SystemExit(f'Invalid MGXC{version} master (regenerate content, no migration): {file}')
        at=10;identity=None
        while at<len(data)-4:
            tag,revision,flags,length=struct.unpack_from('<4sHHI',data,at);at+=12
            if at+length>len(data)-4:raise SystemExit(f'Invalid frame: {file}')
            if tag==b'IDEN':
                if identity is not None or revision!=1 or flags or length!=41:raise SystemExit(f'Invalid identity frame: {file}')
                identity=data[at:at+length]
            at+=length
        expected=assignments.get(relative)
        if not expected or identity is None or identity[:16].hex()!=expected['guid'] or struct.unpack_from('<I',identity,16)[0]!=expected['revision'] or identity[20]!=1 or any(identity[21:]):raise SystemExit(f'Factory identity differs from fixed allocation: {file}')
        if not relative.startswith('KITS/' if kind==2 else 'PRESETS/') or not relative.endswith('.mgxk' if kind==2 else '.mgxp'):raise SystemExit(f'Kind/path mismatch: {file}')
        path='FACTORY/'+relative.split('/')[0]+'/LIBRARY/'+file.name
        if path.casefold() in seen:raise SystemExit(f'Duplicate factory path: {path}')
        seen.add(path.casefold());blob=pack(data);entries.append((path,len(data),len(packed),len(blob),hashlib.sha256(data).digest()));packed.extend(blob)
    if (not entries and required) or max((x[1] for x in entries),default=0)>131072:raise SystemExit('Missing/oversized masters')
    text='// Generated by tools/content/factory_library_pack.py; GBL1 boot-only packing.\n'
    text+=f'inline constexpr unsigned kFactoryLibraryFormatVersion={version};\n'
    text+='inline constexpr unsigned kFactoryLibraryPacking=1;\n'
    text+=f'inline constexpr unsigned kFactoryLibraryCount={len(entries)},kFactoryLibraryMaxBytes={max((x[1] for x in entries),default=0)};\n'
    text+='inline constexpr uint8_t kFactoryLibraryPacked[]={\n'+(' 0,\n' if not packed else '')
    text+=''.join(' '+','.join(f'0x{x:02x}' for x in packed[i:i+24])+',\n' for i in range(0,len(packed),24))+'};\n'
    text+='inline constexpr FactoryLibraryEntry kFactoryLibrary[]={\n'+(' {nullptr,0,0,0,{}},\n' if not entries else '')
    for path,raw,offset,size,digest in entries:text+=' {'+json.dumps(path)+f',{raw},{offset},{size},'+'{'+','.join(f'0x{x:02x}' for x in digest)+'}},\n'
    text+='};\n';target=ROOT/'src/generated/factory_library.inc'
    if a.write:target.write_text(text)
    elif not target.exists() or target.read_text()!=text:raise SystemExit('Factory library packing differs; regenerate with --write')
    print(f'Factory library: {len(entries)} files, {sum(x[1] for x in entries)} raw bytes -> {len(packed)} packed bytes; max scratch {max((x[1] for x in entries),default=0)}')
if __name__=='__main__':main()
