"""Original lossless fourth-difference Rice packing of the immutable AKWF bank."""
import struct
import zlib


def pack(values):
    assert len(values) == 128 * 7 * 256
    output = bytearray()
    for base in range(0, len(values), 256):
        state = [0] * 4
        codes = []
        for value in values[base:base + 256]:
            value = int(value)
            assert -32768 <= value <= 32767
            residual = value
            for level in range(4):
                residual, state[level] = residual - state[level], residual
            codes.append(residual * 2 if residual >= 0 else -residual * 2 - 1)
        for group in range(0, 256, 16):
            chunk = codes[group:group + 16]
            # Adapt to the local mip spectrum, with deterministic tie breaking.
            exponent = min(range(20), key=lambda k: sum((v >> k) + 1 + k for v in chunk))
            output.append(exponent)
            pending = bits = 0
            def bit(value):
                nonlocal pending, bits
                pending |= value << bits
                bits += 1
                if bits == 8:
                    output.append(pending)
                    pending = bits = 0
            for code in chunk:
                for _ in range(code >> exponent):
                    bit(0)
                bit(1)
                for shift in range(exponent):
                    bit((code >> shift) & 1)
            if bits:
                output.append(pending)
    raw = struct.pack('<' + 'h' * len(values), *values)
    return bytes(output), zlib.crc32(raw)


def write_packed(path, values):
    packed, crc = pack(values)
    with path.open('w') as f:
        f.write('// Generated by tools/content/generate-wavetable.py; AKWF CC0, see third_party/akwf/manifest.json.\n')
        f.write('// Lossless signed fourth differences (reset per mip), Rice exponent and alignment per16 samples.\n')
        f.write(f'static constexpr uint32_t kWavetableCrc=0x{crc:08x}u;\n')
        f.write('static const uint8_t kWavetablePacked[]={\n')
        for at in range(0, len(packed), 32):
            f.write(','.join(map(str, packed[at:at+32])) + ',\n')
        f.write('};\n')
    return len(packed), crc
