#!/usr/bin/env python3
"""Generate the 96 kHz polyphase boundary filter, and measure its response."""
from pathlib import Path
import numpy as np,json
n=np.arange(193)-96
h=2*14500/96000*np.sinc(2*14500/96000*n)*np.kaiser(193,9)
h/=h.sum()
# Same coefficients for rational 2:3 and 3:2 conversion; gain is L.
h=h.astype(np.float32)
Path('src/texture_rate_coefficients.h').write_text('#pragma once\n// Generated by tools/fidelity/rate_filter.py; 193 taps, Kaiser beta 9.\nnamespace groove {\nstatic constexpr float kTextureRateFilter[]={\n'+',\n'.join(' '+', '.join(f'{float(x):.10e}f' for x in h[i:i+6]) for i in range(0,len(h),6))+'\n};\n}\n')
f=np.linspace(0,48000,96001);response=abs(np.fft.rfft(h,192000));db=20*np.log10(np.maximum(response,1e-15))
r={'virtual_rate':96000,'taps':193,'group_delay_seconds_per_boundary':.001,'passband_0_13000_max_abs_db':float(abs(db[f<=13000]).max()),'stopband_16000_48000_max_db':float(db[f>=16000].max())}
Path('build/fidelity/texture-rate-filter.json').write_text(json.dumps(r,indent=2)+'\n');print(r)
assert r['passband_0_13000_max_abs_db']<.01 and r['stopband_16000_48000_max_db']< -80
