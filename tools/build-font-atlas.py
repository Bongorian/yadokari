#!/usr/bin/env python3
"""Deterministic A4 UI atlas: Barlow Semi Condensed with frozen tnum.

Run ui-fonts.py first. Only raster data enters Circle; no runtime font I/O.
"""
from pathlib import Path
import hashlib,json,math,importlib.util
from PIL import Image,ImageDraw,ImageFont
root=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('ui_fonts',root/'tools/ui-fonts.py');inputs=importlib.util.module_from_spec(spec);spec.loader.exec_module(inputs)
notices=[root/'third_party/fonts'/family/'OFL.txt' for family in ('barlow-semi-condensed',)]
notice='\n\n'.join(p.read_text() for p in notices)
lines=['// Generated by tools/build-font-atlas.py. OFL notices: third_party/fonts/.','#pragma once','#include <stdint.h>','namespace groove { namespace ui {',
'enum class FontRole:uint8_t { Small, Body, Heading, Number, Bold, Knob };',
'struct Glyph { uint32_t code,offset; int16_t advance; int8_t x,y; uint8_t w,h; };',
'struct Kern { uint16_t pair; int16_t shift; };',
'struct FontFace { const Glyph* glyphs; unsigned count; const uint8_t* coverage; const Kern* kern; unsigned kern_count; uint8_t size,cap_height,line_height,tracking; const char* notice; };',
'inline constexpr const char* font_family="Barlow Semi Condensed";',
'inline constexpr const char font_license[]='+json.dumps(notice)+';']
manifest={'families':['Barlow Semi Condensed'],'license_notices':[str(p.relative_to(root)) for p in notices],'numeric_feature':'tnum frozen into outlines and advances','fonts':[]};total=0
for role,numeric,size,line_height,path,chars in inputs.faces():
 name=role+('_Figures' if numeric else '');font=ImageFont.truetype(str(path),size*4);glyphs=[];data=[]
 for cp in chars:
  c=chr(cp);bounds=font.getbbox(c,anchor='ls');left=math.floor(bounds[0]/4);top=math.floor(bounds[1]/4);right=math.ceil(bounds[2]/4);bottom=math.ceil(bounds[3]/4);w=max(0,right-left);h=max(0,bottom-top)
  im=Image.new('L',(max(1,w*4),max(1,h*4)));ImageDraw.Draw(im).text((-left*4,-top*4),c,font=font,fill=255,anchor='ls');im=im.resize((max(1,w),max(1,h)),Image.Resampling.LANCZOS)
  glyphs.append((cp,len(data),round(font.getlength(c)*16),left,top,w,h));samples=[round(v*15/255) for v in im.getdata()] if w*h else []
  data.extend((samples[i]<<4)|(samples[i+1] if i+1<len(samples) else 0) for i in range(0,len(samples),2))
 kern=[]
 if not numeric:
  for a in range(32,127):
   for b in range(32,127):
    shift=round((font.getlength(chr(a)+chr(b))-font.getlength(chr(a))-font.getlength(chr(b)))*16)
    if shift:kern.append(((a<<8)|b,shift))
 cap=math.ceil(-font.getbbox('H',anchor='ls')[1]/4);tracking=1 if role=='Small' and not numeric else 0
 lines.append(f'inline constexpr Glyph glyphs_{name}[]={{'+','.join('{'+','.join(map(str,g))+'}' for g in glyphs)+'};')
 lines.append(f'inline constexpr uint8_t coverage_{name}[]={{'+','.join(str(x) for x in data)+'};')
 lines.append(f'inline constexpr Kern kern_{name}[]={{'+(','.join('{'+str(k)+','+str(v)+'}' for k,v in kern) if kern else '{0,0}')+'};')
 lines.append(f'inline constexpr FontFace font_{name}={{glyphs_{name},{len(glyphs)},coverage_{name},kern_{name},{len(kern)},{size},{cap},{line_height},{tracking},font_license}};')
 total+=len(data);manifest['fonts'].append({'role':role,'family':'Barlow Semi Condensed','size':size,'cap_height':cap,'line_height':line_height,'tracking_px':tracking,'source_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'coverage_bytes':len(data),'glyphs':len(glyphs),'kern_pairs':len(kern)})
lines+=['inline const FontFace& font_face(FontRole role,bool=false){switch(role){'+''.join(f'case FontRole::{r}:return font_{r};' for r,*_ in inputs.STYLES)+'}return font_Body;}','}}']
(root/'src/ui/font_atlas.h').write_text('\n'.join(lines)+'\n');(root/'assets/fonts/atlas.json').write_text(json.dumps(manifest,indent=2)+'\n');(root/'assets/fonts/LICENSE.txt').write_text(notice)
print(f'Barlow atlas: {total} A4 coverage bytes; {sum(f["kern_pairs"] for f in manifest["fonts"])} kerning pairs')
