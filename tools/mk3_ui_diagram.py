#!/usr/bin/env python3
"""Render the reviewed panel diagram with the actual shared STEP framebuffer."""
from pathlib import Path
import base64
import shutil
import struct
import zlib
from html import escape

root = Path(__file__).resolve().parents[1]
raw = (root / 'build/mk3-ui-STEP.ppm').read_bytes().split(b'\n', 3)
assert raw[:3] == [b'P6', b'960 272', b'255'] and len(raw[3]) == 960 * 272 * 3
pixels = raw[3]
def png(width, height, rgb):
    def chunk(name, data):
        return struct.pack('>I', len(data)) + name + data + struct.pack('>I', zlib.crc32(name + data))
    rows = b''.join(b'\0' + rgb[y * width * 3:(y + 1) * width * 3] for y in range(height))
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 2, 0, 0, 0)) + chunk(b'IDAT', zlib.compress(rows)) + chunk(b'IEND', b'')
output = root / 'build/ui-preview'
output.mkdir(parents=True, exist_ok=True)
images = output / 'images'
images.mkdir(exist_ok=True)
shutil.copyfile(root / 'build/mk3-surface.tsv', output / 'mk3-control-map.tsv')
(images / 'mk3-step.png').write_bytes(png(960, 272, pixels))
for path in sorted((root/'build').glob('mk3-ui-*.ppm')):
    mode = path.stem.removeprefix('mk3-ui-')
    if mode.startswith('MOTION-'): continue
    data = path.read_bytes().split(b'\n', 3)[3]
    (images / f'mk3-{mode.lower()}.png').write_bytes(png(960, 272, data))
svg = ['<svg xmlns="http://www.w3.org/2000/svg" width="1440" height="1430" viewBox="0 0 1440 1430">', '<title>MASCHINE MK3 physical controls and groovebox UI blueprint</title>', '<desc>Placement follows the user reference. Screens are generated by the actual shared renderer; annotations describe a design, including future functions.</desc>']
def box(x, y, w, h, color, radius=5, stroke='#4a5662'):
    svg.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{radius}" fill="{color}" stroke="{stroke}"/>')
def text(x, y, value, size=14, color='#e5edf4'):
    svg.append(f'<text x="{x}" y="{y}" font-family="sans-serif" font-size="{size}" fill="{color}">{escape(value)}</text>')
def button(x, y, name, secondary='', w=120, h=48):
    box(x, y, w, h, '#27313d')
    text(x+8, y+20, name, 13)
    if secondary: text(x+8, y+37, secondary, 11, '#91adbb')
box(0, 0, 1440, 1430, '#101822', 0)
text(32, 34, 'MASCHINE MK3 / GROOVEBOX UI BLUEPRINT', 24, '#64dfc7')
text(32, 56, 'Panel layout: supplied photo + NI manual. Functional annotations are a design; physical LEDs remain uncalibrated.', 14)
box(20, 74, 1400, 1244, '#19212c', 16)
left = [('CHANNEL','MIDI / routing'),('ARRANGER','clips / chain'),('BROWSER','samples / presets'),('PAGE LEFT','parameter bank'),('FILE','SHIFT: SAVE'),('AUTO','hold: automation')]
right = [('PLUG-IN','sound engine'),('MIXER','levels / sends'),('SAMPLING','sample / capture'),('PAGE RIGHT','parameter bank'),('SETTINGS','SHIFT: UPDATE'),('MACRO','Set / 8 controls')]
for row, pair in enumerate(zip(left, right)):
    for col, item in enumerate(pair): button(60+col*140, 105+row*58, *item)
for side, x in enumerate([380,900]):
    for col in range(4):
        button(x+col*120,105,f'BUTTON {side*4+col+1}',w=112,h=34)
    rgb = b''.join(pixels[(y*960+side*480)*3:(y*960+side*480+480)*3] for y in range(272))
    data = base64.b64encode(png(480,272,rgb)).decode()
    svg.append(f'<image x="{x}" y="160" width="480" height="272" href="data:image/png;base64,{data}"/>')
    text(x, 455, '480 x 272 / '+('structure + steps' if side==0 else 'selected sound + performance'), 14, '#64dfc7')
    for col in range(4):
        cx=x+58+120*col
        svg.append(f'<circle cx="{cx}" cy="491" r="25" fill="#364455" stroke="#91adbb"/>')
        text(cx-20,535,f'KNOB {side*4+col+1}',11)
text(380,565,'Each encoder edits the value immediately above it. Touch highlights that column.',15)
svg.append('<circle cx="145" cy="650" r="65" fill="#364455" stroke="#91adbb"/>')
text(110,647,'4-D PUSH',14)
text(104,670,'turn / UDLR',12)
for x,y in [(145,575),(70,650),(220,650),(145,725)]: svg.append(f'<circle cx="{x}" cy="{y}" r="4" fill="#91adbb"/>')
for i,(name,sec) in enumerate([('VOLUME','Velocity'),('SWING','Position'),('TEMPO','Tune')]):button(260,590+i*58,name,sec)
button(410,590,'NOTE REPEAT','Arp',w=150,h=90)
button(410,700,'LOCK','Ext. Lock / A-B',w=150)
for i,(name,sec) in enumerate([('PITCH','pitch bend'),('MOD','modulation'),('PERFORM','Morph / FX'),('NOTES','strum')]):button(60+i*130,800,name,sec)
for i in range(25):svg.append(f'<circle cx="{76+i*21}" cy="872" r="3" fill="#64dfc7"/>')
box(60,890,530,47,'#0c131b')
text(62,960,'SMART STRIP / independent performance layer',15,'#64dfc7')
for i in range(8):button(60+(i%4)*130,990+(i//4)*65,chr(65+i),f'TRACK {i+1} / SHIFT {i+9}',w=120,h=54)
for row, names in enumerate([['RESTART','ERASE','TAP','FOLLOW'],['PLAY','REC','STOP','SHIFT']]):
    subs=[['Loop','Replace','Metro','Grid'],['green','red','white','modifier']][row]
    for col,name in enumerate(names):button(60+col*130,1160+row*65,name,subs[col],w=120,h=54)
button(620,590,'FIXED VEL','16 Vel',w=110)
for i,name in enumerate(['PAD MODE','KEYBOARD','CHORDS','STEP']):button(760+i*156,590,name,w=144)
for i,(name,sec) in enumerate([('SCENE','scene launch'),('PATTERN','clip / pattern'),('EVENTS','step detail'),('VARIATION','Navigate'),('DUPLICATE','Double'),('SELECT','no trigger'),('SOLO','hold overlay'),('MUTE','Choke')]):button(620,665+i*75,name,sec,w=110,h=62)
secondary=['Undo','Redo','Step Undo','Step Redo','Quantize','Quantize 50%','Nudge left','Nudge right','Clear','Clear Auto','Copy','Paste','Semitone -','Semitone +','Octave -','Octave +']
colors=['#b7464b','#c5b444','#488ba0','#488ba0','#c5b444','#c5b444','#3eaa9a','#488ba0','#b58d3c','#b58d3c','#b58d3c','#b58d3c','#3eaa9a','#3eaa9a','#3eaa9a','#3eaa9a']
for row in range(4):
    for col in range(4):
        i=(3-row)*4+col;x=760+col*156;y=665+row*148
        box(x,y,144,134,colors[i],8)
        text(x+10,y+25,f'PAD {i+1}',17,'#09121c')
        text(x+10,y+50,secondary[i],13,'#09121c')
text(38,1347,'LED contract: fixed-color buttons vs indexed-color pads/groups. Palette/brightness profiles require hardware capture.',15)
text(38,1373,'Do not infer 24-bit LED colors from this drawing. Annotations are a design blueprint; consult the current manual for supported actions.',15)
text(38,1400,'Rebuild: make ui-preview | Source audit + current/planned mappings: docs/user-manual.ja.md',14,'#64dfc7')
svg.append('</svg>')
(output/'mk3-ui-wireframe.svg').write_text('\n'.join(svg)+'\n')
print('Wrote physical panel blueprint and shared-renderer screenshots')
